const { contextBridge, ipcRenderer } = require('electron');

const send = (ch, arg) => ipcRenderer.send(ch, arg);

contextBridge.exposeInMainWorld('pt', {
  platform: process.platform,
  getState: () => ipcRenderer.invoke('state:get'),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onFocusAddress: (fn) => ipcRenderer.on('focus-address', () => fn()),
  openPicker: (url, groupId) => ipcRenderer.send('picker:open', url || null, groupId || null),
  createGroup: (ids) => send('group:create', ids),
  showGroup: (id) => send('group:show', id),
  addToGroup: (groupId, tabId) => send('group:add', { groupId, tabId }),
  removeFromGroup: (tabId) => send('group:remove', tabId),
  renameGroup: (id, name) => send('group:rename', { id, name }),
  groupMenu: (id) => send('group:menu', id),
  onSelectMode: (fn) => ipcRenderer.on('select-mode', (_e, tabId) => fn(tabId)),
  onGroupRename: (fn) => ipcRenderer.on('group-rename', (_e, id) => fn(id)),
  closePicker: () => send('picker:close'),
  choose: (slot) => send('picker:choose', slot),
  closeTab: (id) => send('tab:close', id),
  activateTab: (id) => send('tab:activate', id),
  tabMenu: (id) => send('tab:menu', id),
  moveTab: (id, toIndex) => send('tab:move', { id, toIndex }),
  dragEnd: (id) => send('tab:dragEnd', id),
  toggleGrid: () => send('grid:toggle'),
  setDragging: (on) => send('ui:dragging', !!on),
  go: (text) => send('nav:go', text),
  back: () => send('nav:back'),
  forward: () => send('nav:forward'),
  reload: () => send('nav:reload'),
  stop: () => send('nav:stop'),
  nextIp: (key) => send('slot:next', key),
  checkSlot: (key) => send('slot:check', key),
  importProxies: (text, type, color) => ipcRenderer.invoke('proxy:import', { text, type, color }),
  updateProxy: (id, patch) => send('proxy:update', { id, patch }),
  deleteProxy: (id) => send('proxy:delete', id),
  deleteDead: () => send('proxy:deleteDead'),
  testProxy: (id) => send('proxy:test', id),
  testAll: () => send('proxy:testAll'),
  setSettings: (patch) => send('settings:set', patch),
  setDrawer: (open) => send('ui:drawer', open),
  clearNotice: () => send('notice:clear'),
  pwAnswer: (id, action) => send('pw:answer', { id, action }),
  pwReveal: (id) => ipcRenderer.invoke('pw:reveal', id),
  pwDelete: (id) => send('pw:delete', id),
  pwUnnever: (origin) => send('pw:unnever', origin),
});
